def columns(table: str) -> list[str]:
    return [name for name, _, _ in TABLES[table]["columns"]]


def conform(df: pd.DataFrame, table: str, loaded_at=None) -> pd.DataFrame:
    """Return `df` with exactly the table's columns, in order, with the right dtypes.
    Unknown columns are an error: a silent drop would hide a typo."""
    spec = TABLES[table]["columns"]
    names = [name for name, _, _ in spec]
    df = df.copy()
    if "updated_at" in names and "updated_at" not in df.columns:
        df["updated_at"] = loaded_at or pd.Timestamp.now(tz="UTC")
    extra = set(df.columns) - set(names)
    if extra:
        raise ValueError(f"{table}: columns not in schema: {sorted(extra)}")
    out = pd.DataFrame(index=df.index)
    for name, kind, _ in spec:
        col = df[name] if name in df.columns else pd.Series([None] * len(df), index=df.index, dtype=object)
        if kind == F:
            out[name] = pd.to_numeric(col, errors="coerce").astype("float64")
        elif kind == I:
            out[name] = pd.to_numeric(col, errors="coerce").round().astype("Int64")
        elif kind == D:
            out[name] = pd.to_datetime(col, errors="coerce").dt.tz_localize(None).dt.normalize()
        elif kind == T:
            out[name] = pd.to_datetime(col, errors="coerce", utc=True)
        elif kind == B:
            out[name] = col.astype("boolean")
        else:
            out[name] = col.astype(object).where(col.notna(), None)
    return out.reset_index(drop=True)


def to_ndjson(df: pd.DataFrame, table: str) -> str:
    """Serialise a conformed frame as newline-delimited JSON, the format BigQuery loads."""
    out = df.copy()
    for name, kind, _ in TABLES[table]["columns"]:
        if kind == D:
            out[name] = out[name].dt.strftime("%Y-%m-%d")
        elif kind == T:
            out[name] = out[name].dt.strftime("%Y-%m-%dT%H:%M:%SZ")
    return out.to_json(orient="records", lines=True)
